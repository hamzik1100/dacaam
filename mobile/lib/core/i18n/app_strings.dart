import 'package:flutter/widgets.dart';

import '../utils/enums.dart';

/// Somali-first string catalogue.
///
/// Somali (`so`) is the default and the authoritative list of keys; English
/// falls back per-key, so a missing translation degrades to English rather
/// than to a raw key. Provided via an [InheritedWidget] above the navigator so
/// switching language in Settings rebuilds every screen immediately.
class AppStrings extends InheritedWidget {
  AppStrings({super.key, required this.language, required super.child}) {
    // Mirrored into a static so code with no BuildContext can still speak the
    // user's language. Only the transport layer needs this: an ApiException
    // carries its message as text, and the fifty-odd screens that show one
    // have no idea whether they are printing a validation error or "no
    // internet". Localising at the throw site fixes every one of them at once.
    _current = language;
  }

  final AppLanguage language;

  static AppLanguage _current = AppLanguage.somali;

  /// Translates without a context. Prefer `context.t` everywhere a context
  /// exists — this is for the seam below the widget tree.
  static String tr(String key) => _current == AppLanguage.somali
      ? (_so[key] ?? _en[key] ?? key)
      : (_en[key] ?? _so[key] ?? key);

  static AppStrings of(BuildContext context) {
    final AppStrings? result = context
        .dependOnInheritedWidgetOfExactType<AppStrings>();
    assert(result != null, 'No AppStrings found above this widget');
    return result!;
  }

  String t(String key) {
    if (language == AppLanguage.somali) {
      return _so[key] ?? _en[key] ?? key;
    }
    return _en[key] ?? _so[key] ?? key;
  }

  /// `t('itemsCount', {'n': '8'})` -> `8 Alaab`
  String tp(String key, Map<String, String> args) {
    String out = t(key);
    args.forEach((String k, String v) => out = out.replaceAll('{$k}', v));
    return out;
  }

  @override
  bool updateShouldNotify(AppStrings oldWidget) =>
      oldWidget.language != language;
}

extension StringsX on BuildContext {
  AppStrings get s => AppStrings.of(this);

  String t(String key) => AppStrings.of(this).t(key);

  String tp(String key, Map<String, String> args) =>
      AppStrings.of(this).tp(key, args);

  AppLanguage get lang => AppStrings.of(this).language;
}

